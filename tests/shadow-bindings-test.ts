import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {check,show} from '../packages/dari-core/src/compiler.ts';
import {resolve} from './support.ts';
import {sqlite} from '../packages/dari/src/adapters/sqlite.ts';
import {createFixtureModel} from '../packages/dari-core/src/testing/model.ts';
const db=new DatabaseSync(':memory:');
const prefix='data input=table([{n:1},{n:2},{n:3}]);';
function local(body:string){return resolve(check(prefix+`data result=query! {${body}};answer tree! {Answer [Table(data =result)]};`),sqlite(db)).values.result;}
try{
 assert.deepEqual(local(`let r=from(input);let r=r |> filter(r.n>1);let old=r;let r=r |> project({text:"new"}).as!(out);r |> order_by(asc(r.text)) |> top(2)`),[{text:'new'},{text:'new'}]);
 assert.deepEqual(local(`let r=from(input);let old=r;let r=r |> filter(r.n>1);old |> project({n:old.n}).as!(sorted) |> order_by(asc(sorted.n)) |> top(3)`),[{n:1},{n:2},{n:3}]);
 assert.deepEqual(local(`from(input).as!(r) |> filter(r.n>1).as!(r) |> project({n:r.n+10}).as!(r) |> order_by(desc(r.n)) |> top(2)`),[{n:13},{n:12}]);
 assert.deepEqual(local(`let r=from(input).as!(r);let saved=r;let r=r |> project({text:"new"}).as!(r);saved |> project({n:saved.n}).as!(sorted) |> order_by(asc(sorted.n)) |> top(3)`),[{n:1},{n:2},{n:3}]);
 assert.deepEqual(local(`let r=from(input);r.as!(r) |> project({n:r.n}).as!(r) |> order_by(asc(r.n)) |> top(1)`),[{n:1}]);
 const global=`data n=2;data r=table([{n:1},{n:2},{n:3}]);data result=query! {let r=from(r);let n=n+1;r |> filter(r.n<n) |> project({n:r.n}).as!(r) |> order_by(asc(r.n)) |> top(3)};answer tree! {Answer [Table(data =result)]};`;
 assert.deepEqual(resolve(check(global),sqlite(db)).values.result,[{n:1},{n:2}]);
 assert.throws(()=>local(`let r=r |> project({n:r.n}).as!(out);r`),/Unknown relation binding/);
 const compileLocal=(body:string)=>check(prefix+`data result=query! {${body}};answer tree! {Answer [Table(data=result)]};`);
 const warnings=(body:string)=>compileLocal(body).warnings.filter(d=>d.code==='let-alias-shadow');
 const simple='let r=from(input).as!(r);r |> order_by(asc(r.n)) |> top(2)';
 const redundant=warnings(simple);
 assert.equal(redundant.length,1);
 assert.match(redundant[0].message,/postfix binding is unused/);
 assert.equal(redundant[0].at,(prefix+'data result=query! {').length+simple.indexOf('as!(r)')+4);
 assert.equal(redundant[0].asset,'result');
 assert.match(redundant[0].suggestion!,/let rows = from/);
 const used=warnings('let r=from(input).as!(r) |> filter(r.n>1);r |> order_by(asc(r.n)) |> top(2)');
 assert.equal(used.length,1);
 assert(!used[0].message.includes('unused'),'An alias used inside the RHS is shadowed, not unused');
 assert.equal(warnings('let r=from(input).as!(r) |> project({n:r.n});r |> order_by(asc(r.n)) |> top(2)').length,1);
 assert(!warnings('let r=from(input).as!(r) |> project({n:r.n});r |> order_by(asc(r.n)) |> top(2)')[0].message.includes('unused'));
 // Distinct source/plan names are encouraged, and intentional sequential shadow remains valid.
 assert.deepEqual(warnings('let rows=from(input).as!(r) |> filter(r.n>1);rows |> order_by(asc(rows.n)) |> top(2)'),[]);
 assert.deepEqual(warnings('let r=from(input);let r=r |> filter(r.n>1);r |> order_by(asc(r.n)) |> top(2)'),[]);
 assert.deepEqual(warnings('from(input).as!(r) |> filter(r.n>1).as!(r) |> order_by(asc(r.n)) |> top(2)'),[]);
 const {model}=createFixtureModel(sqlite(db));
 db.exec("CREATE TABLE devices(id TEXT,name TEXT,tenant TEXT,cpu REAL);INSERT INTO devices VALUES('a','Alpha','t',10),('b','Beta','t',20)");
 const remote=(body:string)=>check(`data result=query_remote! {${body}};answer tree! {Answer [Table(data =result)]};`,model);
 assert.throws(()=>remote('let rows=from(demo::DeviceKpi).as!(a);let g=group_by_identity(a);g'),/group_by_identity requires a pipeline input/);
 const plain=remote(`let r=from(demo::DeviceKpi);let r=r |> filter(r.name!="Alpha");let r=r |> project({name:r.name,cpu:r.cpu_usage}).as!(out);r |> order_by(desc(r.cpu)) |> top(2)`);
 const sugar=remote(`from(demo::DeviceKpi).as!(r) |> filter(r.name!="Alpha").as!(r) |> project({name:r.name,cpu:r.cpu_usage}).as!(r) |> order_by(desc(r.cpu)) |> top(2)`);
 assert.equal(show(plain.bindings.get('result')!.type),show(sugar.bindings.get('result')!.type));
 assert.deepEqual(resolve(plain,sqlite(db)).values.result,resolve(sugar,sqlite(db)).values.result);
 assert.deepEqual(resolve(plain,sqlite(db)).values.result,[{name:'Beta',cpu:20}]);
 const remoteWarning=remote('let r=from(demo::DeviceKpi).as!(r) |> filter(r.cpu_usage>10.0);r |> project({name:r.name,cpu:r.cpu_usage}) |> order_by(desc(r.cpu_usage)) |> top(2)');
 assert.equal(remoteWarning.warnings.filter(d=>d.code==='let-alias-shadow').length,1);
 const remoteRecommended=remote('let rows=from(demo::DeviceKpi).as!(r) |> filter(r.cpu_usage>10.0);rows |> project({name:r.name,cpu:r.cpu_usage}) |> order_by(desc(r.cpu_usage)) |> top(2)');
 assert(!remoteRecommended.warnings.some(d=>d.code==='let-alias-shadow'));
 console.log('Lexical shadow: local/remote let and as!, type changes, branch snapshots, global captures and equivalent plans passed');
}finally{db.close();}
